#!/usr/bin/env python3
"""Deploy the static build (app/landing/build) to the seohost shared hosting over FTPS (explicit TLS).

    PUBLIC_SITE_PUBLIC=1 PUBLIC_SITE_ORIGIN=https://enigmalabz.com bun run build
    python3 scripts/deploy-ftp.py [--dry-run] [--generation N]

Credentials: ~/.secrets/seohost-ftp (mode 600, three lines: host, user, password) - never in the repo.
Uploads every build file into public_html/, writes .htaccess (root -> /pl/ or /en/ by Accept-Language,
long cache for hashed assets, gzip), then removes remote files under the directories the build owns that
no longer exist locally (old hashed chunks). Host files outside those directories (cgi-bin, *.shtml) stay.

Asset generation: the live site serves hashed assets from `_app/i<N>/`, and `.htaccess` caches that whole
prefix for a year (`^/_app/i\\d+/`). Vite writes `_app/immutable/`, so a deploy renames that one directory
to `_app/i<N>/` and rewrites the 87 HTML files. `N` comes from `scripts/.generation` (one line, bumped
after a successful upload) so a rollback can repeat a number with `--generation`. `--dry-run` never bumps it.
"""
import ftplib
import io
import ssl
import sys
from pathlib import Path

BUILD = Path(__file__).resolve().parent.parent / "build"
REMOTE_ROOT = "public_html"
OWNED = {"_app", "pl", "en", "media", "fonts", "brand", "scan"}
# user decision 2026-10-21: the methodology stays private (not online); the public build must not ship internal paths
FORBIDDEN_DIRS = ("pl/methodology", "en/methodology")
FORBIDDEN_TEXT = (b"qwen-opt/", b"KERNEL/", b"product/research", b"127.0.0.1:18433", b"192.168.")
# canonical/hreflang/og:url must be absolute on the live site: build with PUBLIC_SITE_ORIGIN=https://...
NEED_ORIGIN = b'rel="canonical" href="https://'
HTACCESS = """# generated by app/landing/scripts/deploy-ftp.py
DirectoryIndex index.html
Options -Indexes
ErrorDocument 404 /404.html
AddDefaultCharset UTF-8
RewriteEngine On

# Strona glowna jednym skokiem, takze z http:// i www: przegladarka po angielsku -> /en/ (302), reszta -> /pl/ (301)
RewriteCond %{HTTP:Accept-Language} ^en [NC]
RewriteRule ^$ https://enigmalabz.com/en/ [R=302,L]
RewriteRule ^$ https://enigmalabz.com/pl/ [R=301,L]

# /index.html -> /pl/, /pl/index.html -> /pl/ (tylko adres wpisany z zewnatrz, nie wewnetrzne DirectoryIndex)
RewriteCond %{THE_REQUEST} ^\\S+\\s/index\\.html[\\s?]
RewriteRule ^index\\.html$ https://enigmalabz.com/pl/ [R=301,L]
RewriteCond %{THE_REQUEST} ^\\S+\\s/(.+/)index\\.html[\\s?]
RewriteRule ^(.+/)index\\.html$ https://enigmalabz.com/$1 [R=301,L]

# www -> bez www, http -> https: jeden skok 301
RewriteCond %{HTTP_HOST} ^www\\. [NC,OR]
RewriteCond %{HTTPS} off
RewriteRule ^(.*)$ https://enigmalabz.com/$1 [R=301,L]

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json image/svg+xml text/plain application/xml text/xml
</IfModule>
<IfModule mod_headers.c>
  Header always set Strict-Transport-Security "max-age=31536000"
  <FilesMatch "\\.(js|css|woff2|avif|webp|png|jpg|svg|ico)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
  <If "%{REQUEST_URI} =~ m#^/_app/i\\d+/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
AddType image/avif .avif
AddType font/woff2 .woff2
AddType image/x-icon .ico
AddCharset UTF-8 .txt .xml .js .css .html
"""

GEN_FILE = Path(__file__).resolve().parent / ".generation"
# The live server already has _app/i2/ and _app/i3/; the first deploy from source writes _app/i4/.
GEN_START = 4
# Vite writes this one directory; `.htaccess` caches `^/_app/i<N>/` for a year.
VITE_ASSETS = "_app/immutable"


def read_generation() -> int:
    if not GEN_FILE.exists():
        return GEN_START
    return int(GEN_FILE.read_text().strip() or GEN_START)


def write_generation(n: int) -> None:
    GEN_FILE.write_text(f"{n}\n")


def generation_arg() -> int | None:
    if "--generation" not in sys.argv:
        return None
    return int(sys.argv[sys.argv.index("--generation") + 1])


def stamp_generation(build: Path, n: int) -> int:
    """Rename `_app/immutable` to `_app/i<N>` and point every HTML file at it.

    Runs after the build (never during local preview, which keeps `immutable/`). Idempotent on a
    build that is already stamped, so a retried deploy does not nest `i4/i4`.
    """
    src = build / VITE_ASSETS
    dst = build / "_app" / f"i{n}"
    if src.exists():
        if dst.exists():
            for p in sorted(src.rglob("*")):
                if p.is_file():
                    target = dst / p.relative_to(src)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    p.replace(target)
            for d in sorted((p for p in src.rglob("*") if p.is_dir()), reverse=True):
                if not any(d.iterdir()):
                    d.rmdir()
            if not any(src.iterdir()):
                src.rmdir()
        else:
            src.rename(dst)
    elif not dst.exists():
        sys.exit(f"no hashed assets: neither {VITE_ASSETS} nor _app/i{n} exists in {build}")
    changed = 0
    for html in build.rglob("*.html"):
        data = html.read_text(encoding="utf-8")
        if VITE_ASSETS in data:
            html.write_text(data.replace(VITE_ASSETS, f"_app/i{n}"), encoding="utf-8")
            changed += 1
    return changed


def copy_404(build: Path) -> bool:
    """`ErrorDocument 404 /404.html` needs the prerendered page at the root."""
    src = build / "404" / "index.html"
    if src.exists():
        (build / "404.html").write_text(src.read_text(encoding="utf-8"), encoding="utf-8")
        return True
    return (build / "404.html").exists()


def connect():
    host, user, pw = (Path.home() / ".secrets/seohost-ftp").read_text().splitlines()[:3]
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE  # the shared host presents a certificate for its own name, not srv124947
    ftp = ftplib.FTP_TLS(host, timeout=60, context=ctx)
    ftp.login(user, pw)
    ftp.prot_p()
    return ftp


def remote_tree(ftp, base):
    files, dirs = set(), set()
    def walk(d):
        try:
            entries = list(ftp.mlsd(d, facts=["type"]))
        except ftplib.error_perm:
            return
        for name, f in entries:
            if name in (".", ".."):
                continue
            p = f"{d}/{name}"
            if f.get("type") == "dir":
                dirs.add(p)
                walk(p)
            elif f.get("type") == "file":
                files.add(p)
    walk(base)
    return files, dirs


def main() -> None:
    dry = "--dry-run" in sys.argv
    gen = generation_arg() or read_generation()
    stamped = stamp_generation(BUILD, gen)
    has_404 = copy_404(BUILD)
    local = sorted(p for p in BUILD.rglob("*") if p.is_file())
    if not local:
        sys.exit("build/ is empty: run `bun run build` first")
    leaks = [p.relative_to(BUILD).as_posix() for p in local if p.relative_to(BUILD).as_posix().startswith(FORBIDDEN_DIRS)]
    leaks += [p.relative_to(BUILD).as_posix() for p in local
              if p.suffix in (".html", ".js", ".json", ".txt") and any(t in p.read_bytes() for t in FORBIDDEN_TEXT)]
    if leaks:
        sys.exit(f"refusing to deploy: not a public build ({len(leaks)} private files/paths, e.g. {leaks[:3]}); "
                 "build with PUBLIC_SITE_PUBLIC=1")
    if NEED_ORIGIN not in (BUILD / "pl" / "index.html").read_bytes():
        sys.exit("refusing to deploy: canonical is not absolute https; build with PUBLIC_SITE_ORIGIN=https://...")
    ftp = connect()
    have_files, have_dirs = remote_tree(ftp, REMOTE_ROOT)
    made = set(have_dirs) | {REMOTE_ROOT}
    n = 0
    for p in local:
        rel = p.relative_to(BUILD).as_posix()
        dst = f"{REMOTE_ROOT}/{rel}"
        parts = dst.split("/")[:-1]
        for i in range(2, len(parts) + 1):
            d = "/".join(parts[:i])
            if d not in made:
                if not dry:
                    try:
                        ftp.mkd(d)
                    except ftplib.error_perm:
                        pass
                made.add(d)
        if not dry:
            with p.open("rb") as fh:
                ftp.storbinary(f"STOR {dst}", fh)
        n += 1
    if not dry:
        ftp.storbinary(f"STOR {REMOTE_ROOT}/.htaccess", io.BytesIO(HTACCESS.encode()))
    want = {f"{REMOTE_ROOT}/{p.relative_to(BUILD).as_posix()}" for p in local}
    stale = sorted(f for f in have_files if f not in want and f.split("/")[1] in OWNED)
    for f in stale:
        if not dry:
            ftp.delete(f)
    ftp.quit()
    if not dry:
        write_generation(gen + 1)
    print(
        f"{'would upload' if dry else 'uploaded'} {n} files, .htaccess, removed {len(stale)} stale files; "
        f"_app/i{gen} ({stamped} HTML rewritten), 404.html={'yes' if has_404 else 'NO'}, "
        f"next generation={gen + 1 if not dry else gen} (dry run never bumps)"
    )


if __name__ == "__main__":
    main()
