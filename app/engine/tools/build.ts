// Compiles single-file Enigma binaries with the UI (dist/ui, from `vite build`) embedded.
//   bun tools/build.ts [--target bun-linux-x64,bun-windows-x64,bun-darwin-arm64]
// Output: dist/bin/enigma-<os>-<arch>[.exe]
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { parseArgs } from 'node:util';

const ROOT = join(import.meta.dir, '..');
const UI = join(ROOT, 'dist', 'ui');
// The entry must sit next to hash-worker.ts: compiled workers resolve relative to the entry's embedded path.
const SERVER = join(ROOT, 'src', 'server');
const OUT = join(ROOT, 'dist', 'bin');
const ALL = ['bun-linux-x64', 'bun-windows-x64', 'bun-darwin-arm64'];

const { values } = parseArgs({ options: { target: { type: 'string', default: ALL.join(',') } } });
const targets = values.target.split(',').map((t) => t.trim()).filter(Boolean);

if (!existsSync(join(UI, 'index.html'))) throw new Error('dist/ui/index.html missing: run `bun run build:ui` first');

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(UI);
const rel = (p: string): string => {
  const r = relative(SERVER, p).split('\\').join('/');
  return r.startsWith('.') ? r : `./${r}`;
};
const imports = files.map((f, i) => `import f${i} from ${JSON.stringify(rel(f))} with { type: 'file' };`);
const entries = files.map((f, i) => `  ${JSON.stringify(relative(UI, f).split('\\').join('/'))}: f${i},`);
const entry = join(SERVER, 'enigma.gen.ts');
writeFileSync(entry, `// generated by tools/build.ts (not committed): embeds dist/ui and runs the CLI
${imports.join('\n')}
import { registerEmbeddedUi } from './api.ts';
import { main } from './main.ts';

registerEmbeddedUi({
${entries.join('\n')}
});
process.exit(await main(process.argv.slice(2)));
`);

mkdirSync(OUT, { recursive: true });
for (const target of targets) {
  const [, os, arch] = target.split('-');
  const name = `enigma-${os === 'darwin' ? 'macos' : os}-${arch}${os === 'windows' ? '.exe' : ''}`;
  const outfile = join(OUT, name);
  const proc = Bun.spawn([
    process.execPath, 'build', '--compile', `--target=${target}`, '--minify', '--sourcemap=none',
    entry, join(ROOT, 'src/server/hash-worker.ts'), '--outfile', outfile,
  ], { cwd: ROOT, stdout: 'inherit', stderr: 'inherit' });
  if ((await proc.exited) !== 0) throw new Error(`bun build failed for ${target}`);
  console.log(`${relative(ROOT, outfile)}  ${(statSync(outfile).size / 1024 ** 2).toFixed(1)} MiB  (${files.length} UI files embedded)`);
}
